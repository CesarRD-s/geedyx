export const catalogs: Record<Locale, Record<MessageKey, string>> = { es, en };

export function supportedLocale(value: string): Locale {
  return value === "en" ? "en" : "es";
}

export function getTranslations(locale: string) {
  const catalog = catalogs[supportedLocale(locale)];
  return (key: MessageKey): string => catalog[key];
}
